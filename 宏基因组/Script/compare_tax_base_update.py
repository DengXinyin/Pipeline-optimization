    # 7. All.taxonomy.csv from original vs update: original is per-gene, update is aggregated.
    lines.append('[INFO] All.taxonomy.csv：上游 anno_original/Annotation/All/All.taxonomy.csv 为逐基因表（约 104 万行），'
                 'Result_update 中 Samples/All/All.taxonomy.csv 为按分类层级聚合表（约 1.3 万行），二者属于不同处理阶段，'
                 '不直接比较 md5。')

    # 8. Taxonomy rank xlsx: verify group means equal sample means
    ranks = ['kingdom', 'phylum', 'class', 'order', 'family', 'genus', 'species']
    sample_cols = ['CK-1', 'CK-2', 'CK-3', 'T-1', 'T-2', 'T-3']
