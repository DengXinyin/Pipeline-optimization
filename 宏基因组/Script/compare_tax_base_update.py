def md5(path):
    h = hashlib.md5()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(8 * 1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def compare_md5(label, path_a, path_b):
    if not os.path.exists(path_a):
        return f'[SKIP] {label}: {path_a} 不存在'
    if not os.path.exists(path_b):
        return f'[SKIP] {label}: {path_b} 不存在'
    a, b = md5(path_a), md5(path_b)
    status = 'PASS' if a == b else 'DIFF'
    return f'[{status}] {label}\n  A: {path_a}\n  B: {path_b}\n  A md5: {a}\n  B md5: {b}'


def compare_excel(label, path_a, path_b, sort_first=True):
    if not os.path.exists(path_a):
        return f'[SKIP] {label}: {path_a} 不存在'
    if not os.path.exists(path_b):
        return f'[SKIP] {label}: {path_b} 不存在'
    try:
        a = pd.ExcelFile(path_a)
        b = pd.ExcelFile(path_b)
        if a.sheet_names != b.sheet_names:
            return f'[DIFF-sheets] {label}: sheet names differ\n  A: {a.sheet_names}\n  B: {b.sheet_names}'
        diffs = []
        for sheet in a.sheet_names:
            df_a = pd.read_excel(path_a, sheet_name=sheet, dtype=str)
            df_b = pd.read_excel(path_b, sheet_name=sheet, dtype=str)
            if sort_first:
                if not df_a.empty:
                    df_a = df_a.sort_values(by=list(df_a.columns), axis=0).reset_index(drop=True)
                if not df_b.empty:
                    df_b = df_b.sort_values(by=list(df_b.columns), axis=0).reset_index(drop=True)
            if df_a.shape != df_b.shape:
                diffs.append(f'{sheet}: shape A{df_a.shape} != B{df_b.shape}')
                continue
            if not df_a.equals(df_b):
                diffs.append(f'{sheet}: values differ')
        if diffs:
            return f'[DIFF-values] {label}\n  ' + '\n  '.join(diffs)
        return f'[PASS] {label}: {path_a} vs {path_b} ({len(a.sheet_names)} sheets)'
    except Exception as e:
        return f'[ERROR] {label}: {e}'


def compare_csv_summary(label, path_a, path_b, sort_cols=None):
    if not os.path.exists(path_a) or not os.path.exists(path_b):
        return f'[SKIP] {label}: 文件缺失'
    try:
        a = pd.read_csv(path_a, dtype=str)
        b = pd.read_csv(path_b, dtype=str)
        if a.shape != b.shape:
            return f'[DIFF] {label}: shape A{a.shape} != B{b.shape}'
        if sort_cols and all(c in a.columns for c in sort_cols):
            a = a.sort_values(by=sort_cols).reset_index(drop=True)
            b = b.sort_values(by=sort_cols).reset_index(drop=True)
        if not a.equals(b):
            return f'[DIFF] {label}: values differ'
        return f'[PASS] {label}: {path_a} vs {path_b} {a.shape}'
    except Exception as e:
        return f'[ERROR] {label}: {e}'


